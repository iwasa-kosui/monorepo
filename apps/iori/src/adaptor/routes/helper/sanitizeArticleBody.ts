import sanitizeHtml from 'sanitize-html';

export const sanitizeArticleBody = (html: string) =>
  sanitizeHtml(html, {
    allowedTags: [
      'p',
      'span',
      'br',
      'a',
      'del',
      'pre',
      'code',
      'em',
      'strong',
      'b',
      'i',
      'u',
      'ul',
      'ol',
      'li',
      'blockquote',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'hr',
      'table',
      'thead',
      'tbody',
      'tr',
      'th',
      'td',
    ],
    allowedClasses: {
      'pre': ['shiki', 'shiki-themes', 'shiki-dark', 'shiki-light', 'github-light', 'github-dark'],
      'code': [
        'language-javascript',
        'language-typescript',
        'language-ts',
        'language-python',
        'language-ruby',
        'language-java',
        'language-cpp',
        'language-html',
        'language-css',
      ],
    },
    allowedAttributes: {
      'a': ['href', 'rel'],
      'pre': ['class'],
    },
    allowedSchemes: ['https', 'http'],
    allowProtocolRelative: false,
    transformTags: {
      a: sanitizeHtml.simpleTransform('a', { rel: 'noopener noreferrer nofollow' }),
    },
  });
